  let lang = localStorage.getItem('ablemark.lang') || 'ru';

  /** Перевод: t('key') или t('key', {placeholders}). */
  function t(key, vars) {
    let s = (dict[lang] && dict[lang][key]);
    if (s === undefined) s = dict.ru[key];
    if (s === undefined) return key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) s = String(s).replaceAll(`{${k}}`, v);
    }
    return s;
  }

  /** Применить переводы ко всем [data-i18n], [data-i18n-ph], [data-i18n-title]. */
  function apply() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-ph]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = t(el.dataset.i18nTitle);
    });
    document.documentElement.lang = lang;
  }

  function setLang(l) {
    if (!dict[l]) return;
    lang = l;
    localStorage.setItem('ablemark.lang', l);
    apply();
  }

  function toggle() {
    setLang(lang === 'ru' ? 'en' : 'ru');
    return lang;
  }

  return { t, apply, setLang, toggle, get lang() { return lang; } };
